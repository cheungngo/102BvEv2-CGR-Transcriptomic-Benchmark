def reversal_metrics(drug_vec, deg_df, gene_subset):
    sub = deg_df[deg_df["symbol"].isin(gene_subset)].set_index("symbol")["log2FC"]
    common = drug_vec.index.intersection(sub.index)
    if len(common) < 10:
        return np.nan, np.nan, len(common)
    d_v = drug_vec.loc[common].values
    g_v = sub.loc[common].values
    if np.all(d_v == 0) or np.all(g_v == 0):
        return np.nan, np.nan, len(common)
    cos_sim = 1.0 - cosine(d_v, g_v)
    rho, _ = spearmanr(d_v, g_v)
    return round(float(cos_sim), 4), round(float(rho), 4), int(len(common))

