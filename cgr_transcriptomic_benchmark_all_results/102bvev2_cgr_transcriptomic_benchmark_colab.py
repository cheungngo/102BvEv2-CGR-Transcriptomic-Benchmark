def parse_persistent_tsv(url):
    resp = SESSION.get(url, timeout=45)
    resp.raise_for_status()
    lines = resp.text.splitlines()
    if len(lines) < 10:
        return pd.Series(dtype=float)
    first_parts = lines[0].split("\t")
    has_header = False
    if len(first_parts) >= 2:
        try:
            float(first_parts[1])
        except ValueError:
            has_header = True
    df = pd.read_csv(
        io.StringIO(resp.text),
        sep="\t",
        header=0 if has_header else None,
        usecols=[0, 1],
        names=["symbol", "val"] if not has_header else None,
    )
    df.columns = ["symbol", "val"]
    df["symbol"] = df["symbol"].astype(str).str.strip().str.upper()
    df["val"] = pd.to_numeric(df["val"], errors="coerce")
    df = df.dropna(subset=["symbol", "val"]).groupby("symbol")["val"].mean()
    return df

def _sort_sigs_deterministic(sigs):
    """Sort signatures deterministically client-side by signature ID (and persistent_id fallback)."""
    return sorted(
        sigs,
        key=lambda s: (
            str(s.get("id", "")),
            str((s.get("meta") or {}).get("persistent_id", "")),
        ),
    )

def query_sigcom_signatures(spec, limit=250):
    pert_names = spec["names"] if isinstance(spec, dict) else ([spec] if isinstance(spec, str) else list(spec))
    pert_ids = spec.get("pert_ids", []) if isinstance(spec, dict) else []

    # 1. Fast indexed lookup by exact case variants of meta.pert_name
    variants = []
    for name in pert_names:
        variants.extend([name, name.lower(), name.upper(), name.title()])
    variants = list(dict.fromkeys(variants))

    fast_query = {
        "filter": {
            "where": {"meta.pert_name": {"inq": variants}},
            "limit": limit,
        }
    }
    r = SESSION.post(f"{SIGCOM_META}/signatures/find", json=fast_query, timeout=90)
    r.raise_for_status()
    sigs = r.json()
    if isinstance(sigs, list) and sigs:
        return _sort_sigs_deterministic(sigs)

    # 2. Fast indexed lookup by Broad pert_id (BRD-...) if provided
    if pert_ids:
        id_query = {
            "filter": {
                "where": {"meta.pert_id": {"inq": pert_ids}},
                "limit": limit,
            }
        }
        r = SESSION.post(f"{SIGCOM_META}/signatures/find", json=id_query, timeout=90)
        r.raise_for_status()
        sigs = r.json()
        if isinstance(sigs, list) and sigs:
            return _sort_sigs_deterministic(sigs)

    # 3. Optional substring ilike fallback (disabled by default to prevent SigCom 503/timeouts)
    if ENABLE_ILIKE_FALLBACK:
        try:
            ilike_query = {
                "filter": {
                    "where": {"meta.pert_name": {"ilike": f"%{pert_names[0]}%"}},
                    "limit": limit,
                }
            }
            r = SESSION.post(f"{SIGCOM_META}/signatures/find", json=ilike_query, timeout=90)
            r.raise_for_status()
            sigs = r.json()
            if isinstance(sigs, list) and sigs:
                return _sort_sigs_deterministic(sigs)
        except requests.exceptions.RequestException:
            pass

    return []

def fetch_l1000_consensus(spec, prefer_neural=None, max_sigs=None, limit=250):
    if prefer_neural is None:
        prefer_neural = PREFER_NEURAL_CELLS
    if max_sigs is None:
        max_sigs = MAX_SIGS_PER_COMPOUND

    primary_name = spec["names"][0] if isinstance(spec, dict) else str(spec)
    try:
        sigs = query_sigcom_signatures(spec, limit=limit)
    except requests.exceptions.RequestException as e:
        print(f"    [ERR] Query failed for '{primary_name}': {e}")
        return pd.Series(dtype=float), {"n_found": 0, "n_used": 0, "cell_mode": "timeout_or_error"}

    # Client-side filter: exclude genetic perturbations & keep deterministic order
    sigs = _sort_sigs_deterministic([
        s for s in sigs
        if str((s.get("meta") or {}).get("pert_type", "")).upper() not in GENETIC_PERT_TYPES
    ])
    if not sigs:
        return pd.Series(dtype=float), {"n_found": 0, "n_used": 0, "cell_mode": "none"}

    neural_recs = [s for s in sigs if str((s.get("meta") or {}).get("cell_line", "")).upper() in NEURAL_CELLS]
    if prefer_neural and len(neural_recs) >= 2:
        chosen = neural_recs[:max_sigs]
        cell_mode = "neural"
    else:
        chosen = sigs[:max_sigs]
        cell_mode = "all_cell_lines"

    # Primary path: download per-signature TSV via S3 persistent_id URL
    vectors = []
    for s in chosen:
        pid_url = (s.get("meta") or {}).get("persistent_id") or s.get("persistent_id")
        if pid_url and str(pid_url).startswith("http"):
            try:
                v = parse_persistent_tsv(pid_url)
                if not v.empty:
                    vectors.append(v)
            except Exception:
                continue

    if vectors:
        mat = pd.concat(vectors, axis=1)
        consensus = mat.median(axis=1)
        return consensus, {"n_found": len(sigs), "n_used": len(vectors), "cell_mode": cell_mode}

    # Fallback path: SigCom Data API /fetch
    try:
        sig_ids = [s["id"] for s in chosen if "id" in s]
        data_resp = SESSION.post(f"{SIGCOM_DATA}/fetch", json={"signatures": sig_ids}, timeout=90).json()
        if isinstance(data_resp, dict) and "data" in data_resp:
            mat = pd.DataFrame(data_resp["data"])
            mat.index = mat.index.astype(str).str.upper()
            return mat.median(axis=1), {"n_found": len(sigs), "n_used": mat.shape[1], "cell_mode": f"{cell_mode}_data_api"}
    except Exception:
        pass

    return pd.Series(dtype=float), {"n_found": len(sigs), "n_used": 0, "cell_mode": "fetch_failed"}

def zscore_series(s):
    std = s.std(ddof=0)
    if pd.isna(std) or std == 0:
        return s
    return (s - s.mean()) / std

