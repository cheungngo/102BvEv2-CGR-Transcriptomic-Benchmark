def map_ensembl_to_symbol(ensembl_ids):
    """Map Ensembl gene IDs to HGNC symbols via MyGene.info batch API."""
    clean_ids = list({str(e).split(".")[0] for e in ensembl_ids if pd.notna(e)})
    mapping = {}
    for i in range(0, len(clean_ids), 1000):
        chunk = clean_ids[i:i+1000]
        r = requests.post(
            "https://mygene.info/v3/gene",
            json={"ids": chunk, "fields": "symbol"},
            headers=UA,
            timeout=60,
        )
        if r.ok:
            for item in r.json():
                if isinstance(item, dict) and "symbol" in item and "query" in item:
                    mapping[item["query"]] = item["symbol"]
    return mapping

